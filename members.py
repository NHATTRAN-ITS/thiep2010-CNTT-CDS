def validate_members(data=None):
    data = member_data if data is None else data
    if not data:
        raise ValueError("member_data đang rỗng — hãy thêm ít nhất một người.")
    seen_alias = {}
    for name, info in data.items():
        missing = [key for key in REQUIRED_FIELDS if not str(info.get(key, "")).strip()]
        if missing:
            raise ValueError(f"Thiếu dữ liệu bắt buộc cho '{name}': {', '.join(missing)}")
        alias = str(info.get("alias", "")).strip().lower()
        if alias:
            if alias in seen_alias:
                raise ValueError(
                    f"Alias trùng nhau: '{alias}' dùng cho '{seen_alias[alias]}' và '{name}'."
                )
            seen_alias[alias] = name
    return data
